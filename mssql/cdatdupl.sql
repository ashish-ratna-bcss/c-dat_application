 CREATE Procedure [dbo].[PROCS_NEARBY_TOWER_SEARCH] --PROCS_NEARBY_TOWER_SEARCH 17.48865,78.55464,1000,'',''
(
@Latitude  float =null,
@Longitude float =null,
@Radious Int =null,
@OPERATOR  nvarchar(max)=NULL,
@CELLTOWERID varchar(max)=NULL
)
AS
BEGIN
IF ISNULL(@OPERATOR,'')=''
		SET @OPERATOR = NULL
IF ISNULL(@CELLTOWERID,'')=''
		SET @CELLTOWERID = NULL
IF ISNULL(@Latitude,'')=''
		SET @Latitude = NULL
IF ISNULL(@Longitude,'')=''
		SET @Longitude = NULL
IF ISNULL(@Radious,'')=''
		SET @Radious = NULL
	
DECLARE @lat float
DECLARE @lon float
SET @lat = @Latitude
SET @lon = @Longitude
DECLARE @maxLat float, @minLat float, @maxlon float, @minLon float
DECLARE @R float
DECLARE @distance int= @Radious -- A distance in meters   
SET @R = 6378137 -- Earth
SET @maxLat = @lat + DEGREES(@distance/@R)
SET @minLat = @lat - DEGREES(@distance/@R)

SET @maxLon = @lon + DEGREES((@distance/@R/COS(RADIANS(@lat))))
SET @minLon = @lon - DEGREES((@distance/@R/COS(RADIANS(@lat)))) 

SELECT  ISNULL([TOWER_KEY] ,'') AS TOWER_KEY ,ISNULL([CELLTOWERID],'') AS CELLTOWERID,ISNULL([BTS_ID],'') AS BTS_ID,ISNULL([AREADESCRIPTION],'') AS AREADESCRIPTION,ISNULL([SITEADDRESS],'') AS SITEADDRESS,
