CREATE Procedure [dbo].[Towersearch] --Towersearch  'TATA_TOWER','','TELANGANA'
(
@OPERATOR  nvarchar(max)=NULL,
@CELLTOWERID varchar(max)=NULL,
@STATE varchar(max)=NULL
)
AS
BEGIN
IF ISNULL(@OPERATOR,'')=''
		SET @OPERATOR = NULL
else if @OPERATOR='AIIRCE_TOWER' set @OPERATOR='AIRCEL_TOWER'
else if @OPERATOR='IDEA' set @OPERATOR='IDEA_TOWER'
else if @OPERATOR='TELENOT_TOWER' or @OPERATOR='TELENOR_TOWER'  set @OPERATOR='UNINOR_TOWER'
else if @OPERATOR='ICR_VODA' set @OPERATOR='VODAFONE_TOWER'
else set @OPERATOR=@OPERATOR



IF ISNULL(@CELLTOWERID,'')=''
		SET @CELLTOWERID = NULL


IF ISNULL(@STATE,'')=''
		SET @STATE = NULL
else if @STATE='Andhrapradesh' or @STATE='Telangana' OR @STATE='Telengana' 
OR  @STATE='AP & TS' OR @STATE='AP&TS' OR @STATE= 'TS & AP' OR @STATE='TS&AP' set @STATE='ANDHRA PRADESH'
else if @STATE='GUJARATH' OR @STATE='GUJRAT' set @STATE='GUJARAT'
else if @STATE='Jammu And Kashmir' or @STATE ='JAMMU & KASHMIR' set @STATE='JAMMU_KASHMIR'
else if @STATE='MAHARASTARA' or @state='MAHARASTRA' set @STATE='MAHARASHTRA'
else if @STATE='North East' or @STATE='SIKKIM' or @STATE='ANDAMAN AND NICOBAR ISLANDS' or @state= 'UTTRAKHAND' set @STATE='NORTH_EAST'
else if @STATE='Odisha' set @STATE='ORISSA'
else if @STATE='RAJASTAN' set @STATE='RAJASTHAN'
else if @STATE='Uttar Pradesh (East)' set @STATE='UP_EAST'
else if @STATE='Uttar Pradesh (West)' set @STATE='UP_WEST'
else set @STATE=@STATE




SELECT top 1000  ISNULL([TOWER_KEY] ,'') AS TOWER_KEY ,ISNULL([CELLTOWERID],'') AS CELLTOWERID,ISNULL([BTS_ID],'') AS BTS_ID,ISNULL([AREADESCRIPTION],'') AS AREADESCRIPTION,ISNULL([SITEADDRESS],'') AS SITEADDRESS,
ISNULL([LAT],0) AS LAT,ISNULL([LONG],0)AS LONG ,
ISNULL([AZIMUTH],'') AS AZIMUTH ,ISNULL([OPERATOR] ,'') AS OPERATOR ,ISNULL([STATE],'') AS STATE,ISNULL([OTYPE],'') AS OTYPE,ISNULL([LASTUPDATE],'') AS LASTUPDATE,
	  ISNULL([SITEADDRESS],'') AS SITEADDRESS,
ISNULL([STATE_KEY],'')AS STATE_KEY ,
	  ISNULL([PROVIDER_NAME],'') AS PROVIDER_NAME,ISNULL([PROVIDER_KEY],'') AS PROVIDER_KEY,ISNULL([STATE_CODE],'')AS STATE_CODE ,
	  ISNULL([CELLID],'') AS CELLID   FROM CDATCELLTOWERAREANEW with (nolock)
WHERE

	 (OPERATOR = @OPERATOR or @OPERATOR IS NULL)
	AND (CELLTOWERID LIKE'%'+@CELLTOWERID or @CELLTOWERID IS NULL)
	AND (STATE = @STATE or @STATE IS NULL)
	
END


