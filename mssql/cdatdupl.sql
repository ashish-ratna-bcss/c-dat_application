	  ISNULL([PROVIDER_NAME],'') AS PROVIDER_NAME,ISNULL([PROVIDER_KEY],'') AS PROVIDER_KEY,ISNULL([STATE_CODE],'')AS STATE_CODE ,
	  ISNULL([CELLID],'') AS CELLID   FROM CDATDUPL..CDATCELLTOWER1
WHERE
    ((CAST([LAT] AS float)  Between @minLat And @maxLat )or  @minLat is null And @maxLat is null)
    And ((CAST([LONG] AS float) Between @minLon And @maxLon )or  @minLon is null And @maxLon is null)
	AND (OPERATOR = @OPERATOR or @OPERATOR IS NULL) and  try_convert(Float,[LAT]) is not null and try_convert(Float,[LONG]) is not null
	AND (CELLTOWERID = @CELLTOWERID or @CELLTOWERID IS NULL)
	
